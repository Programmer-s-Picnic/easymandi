'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const file=relative=>fs.readFileSync(path.join(root,relative),'utf8');
const html=file('admin/index.html');
const js=file('admin/operations-desk.js');
const css=file('admin/catalog.css');
const assert=(condition,message)=>{if(!condition)throw Error('Operations Desk guide check failed: '+message)};
const guide=html.match(/<details class="ops-guide" id="opsHowTo">([\s\S]*?)<\/details>/);
assert(!!guide,'collapsible How to Work guide must appear on the desk');
assert(html.indexOf('id="opsHowTo"')<html.indexOf('id="opsKpis"'),'guide should be visible above the queues');
assert(html.includes('<a href="#opsHowTo">How to Work</a>'),'guide must be linked in site navigation');
assert(guide[1].includes('<summary>')&&guide[1].includes('</summary>'),'accessible details/summary control');
const shortcuts=[...guide[1].matchAll(/data-ops-guide-queue="([^"]+)"/g)].map(m=>m[1]);
assert(shortcuts.length===7,'seven workflow shortcuts are expected');
assert(new Set(shortcuts).size===shortcuts.length,'queue shortcut values must be unique');
const selects=[...html.matchAll(/<option value="([^"]+)">/g)].map(m=>m[1]);
for(const queue of shortcuts)assert(selects.includes(queue),'guide shortcut '+queue+' has no corresponding queue');
assert(js.includes("howTo.querySelectorAll('[data-ops-guide-queue]')"),'shortcuts require registered click handlers');
assert(js.includes("howTo.open=false"),'shortcut navigation must close the instructions');
assert(js.includes("if(!window.AdminSession.token)"),'queue links must respect administrator authentication');
assert(css.includes('.ops-guide-content')&&css.includes('@media(max-width:720px)'),'guide should have responsive styling');
assert(html.includes('id="usageGuide"'),'legacy administration guide must be preserved');
assert(html.includes('id="recordsPanel"')&&html.includes('id="productsPanel"'),'legacy admin features must be preserved');
console.log('PASS: Operations Desk guide, seven live queue shortcuts, authentication and existing panels.');
